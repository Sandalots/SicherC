// use the standard io library
#include <stdio.h>

int main() {
    int num1, num2, sum;

    num1 = 2;
    num2 = 3;

    // Calculate the sum
    sum = num1 + num2;

    // Display the result
    printf("The sum of %d and %d is %d.\n", num1, num2, sum);

    return 0;
}